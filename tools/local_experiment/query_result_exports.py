"""Read-only export of the exact contiguous result pages a worksheet received."""
import base64
from copy import deepcopy
from decimal import Decimal
import json
import math
import re

from query_context import QueryError

MAX_RECEIPTS = 4096
MAX_BYTES = 16 * 1024 * 1024
CONTENT_TYPES = {'json': 'application/json; charset=utf-8',
                 'csv': 'text/csv; charset=utf-8',
                 'tsv': 'text/tab-separated-values; charset=utf-8'}


def _unavailable():
    raise QueryError('RESULT_EXPORT_UNAVAILABLE', 409)


def _body(value):
    if (type(value) is not dict or set(value) != {'format', 'request_id', 'worksheet_id', 'received_pages'} or
            type(value['format']) is not str or value['format'] not in CONTENT_TYPES or
            any(type(value[key]) is not str or not value[key].strip() or len(value[key]) > 512
                for key in ('request_id', 'worksheet_id'))):
        raise QueryError('INVALID_RESULT_EXPORT', 400)
    receipts = value['received_pages']
    if type(receipts) is list and len(receipts) > MAX_RECEIPTS:
        raise QueryError('RESULT_EXPORT_TOO_LARGE', 413)
    if (type(receipts) is not list or not 1 <= len(receipts) <= MAX_RECEIPTS or
            any(type(item) is not str or not re.fullmatch(r'[a-zA-Z0-9_-]{1,128}', item) for item in receipts) or
            len(set(receipts)) != len(receipts)):
        raise QueryError('INVALID_RESULT_EXPORT', 400)
    return value


def _cell(value):
    """Integer strings are recursive, including array/map/row cells; bool is distinct."""
    if value is None or type(value) in (str, bool):
        return value
    if type(value) is int:
        return str(value)
    if type(value) is Decimal:
        if not value.is_finite():
            _unavailable()
        return str(value)
    if type(value) is float:
        if not math.isfinite(value):
            _unavailable()
        return value
    if type(value) is list:
        return [_cell(item) for item in value]
    if type(value) is dict and all(type(key) is str for key in value):
        return {key: _cell(item) for key, item in value.items()}
    _unavailable()


def _json(value):
    return json.dumps(value, ensure_ascii=False, allow_nan=False, separators=(',', ':'))


def _serialize(format, columns, rows, range_info, query):
    # Incremental UTF-8 accounting bounds generated bytes without truncating a file.
    output = bytearray()
    def write(text):
        encoded = text.encode('utf-8')
        if len(output) + len(encoded) > MAX_BYTES:
            raise QueryError('RESULT_EXPORT_TOO_LARGE', 413)
        output.extend(encoded)
    if format == 'json':
        write('{"columns":' + _json(columns) + ',"rows":[')
        for index, row in enumerate(rows):
            write((',' if index else '') + _json([_cell(value) for value in row]))
        write('],"encoding":{"integer_cells":"decimal-string"},"range":' + _json(range_info) +
              ',"query":' + _json(query) + '}')
    else:
        separator = ',' if format == 'csv' else '\t'
        def quoted(value):
            return '"' + value.replace('"', '""') + '"'
        write(separator.join(quoted(column['name']) for column in columns) + '\r\n')
        for row in rows:
            cells = []
            for value in row:
                if value is None:
                    cells.append('\\N')
                    continue
                converted = _cell(value)
                if type(converted) in (list, dict, bool, float):
                    converted = _json(converted)
                cells.append(quoted(converted))
            write(separator.join(cells) + '\r\n')
    return bytes(output)


def export(principal, query_id, selected_role, body):
    """Never fetch, execute, wake, cancel, or mutate query state while exporting."""
    import control_store
    import query_service as qs
    body = _body(body)
    row = qs._owned(principal, query_id, selected_role, cleanup=False)
    if row['execution_closure']:
        raise QueryError('EXECUTION_CLOSED', 409)
    pin = qs._pins.get(query_id)
    if pin is None:
        _unavailable()
    with pin.lock:
        row = qs._owned(principal, query_id, selected_role, cleanup=False)
        if row['execution_closure']:
            raise QueryError('EXECUTION_CLOSED', 409)
        context = qs._metadata(row)
        if (row['request_id'] != body['request_id'] or row['worksheet_id'] != body['worksheet_id']):
            raise QueryError('CONTEXT_MISMATCH', 409)
        if pin.plan is not None or row['mode'] == 'dataops':
            _unavailable()
        with control_store.connect() as db:
            if db.execute('SELECT 1 FROM dataops_queries WHERE query_id=?', (query_id,)).fetchone():
                _unavailable()
        if pin.context.public_metadata() != context or pin.headers.get('X-Trino-User') != row['backend_username']:
            _unavailable()
        pages, page, seen = [], pin.initial_response, set()
        for receipt in body['received_pages']:
            if (type(page) is not dict or page.get('result_page_id') != receipt or receipt in seen or
                    page.get('id') != query_id or page.get('request_id') != body['request_id'] or
                    page.get('worksheet_id') != body['worksheet_id'] or page.get('context') != context or
                    page.get('backend_query_id') != row['backend_query_id']):
                _unavailable()
            seen.add(receipt)
            if (page.get('state') not in ('QUEUED', 'RUNNING', 'FINISHED', 'FAILED', 'CANCELED', 'UNKNOWN') or
                    type(page.get('truncated', False)) is not bool):
                _unavailable()
            next_uri = page.get('next_uri')
            prefix = '/api/v1/queries/' + query_id + '/pages/'
            if next_uri is not None and (type(next_uri) is not str or not re.fullmatch(
                    re.escape(prefix) + r'[a-zA-Z0-9_-]+', next_uri)):
                _unavailable()
            try:
                pages.append(deepcopy(page))
            except (RecursionError, ValueError, TypeError):
                _unavailable()
            if len(pages) == len(body['received_pages']):
                break
            if type(next_uri) is not str or not next_uri.startswith(prefix):
                _unavailable()
            token = next_uri[len(prefix):]
            if not re.fullmatch(r'[a-zA-Z0-9_-]+', token):
                _unavailable()
            page = pin.responses.get(token)
        current = qs._owned(principal, query_id, selected_role, cleanup=False)
        if current['execution_closure']:
            raise QueryError('EXECUTION_CLOSED', 409)
        if qs._metadata(current) != context or any(current[k] != row[k] for k in
                ('request_id', 'worksheet_id', 'backend_query_id')):
            _unavailable()
        state = current['state']
    columns, rows = None, []
    for page in pages:
        raw_columns, data = page.get('columns'), page.get('data')
        if type(raw_columns) is not list or type(data) is not list:
            _unavailable()
        if raw_columns:
            normalized = []
            for column in raw_columns:
                if (type(column) is not dict or type(column.get('name')) is not str or
                        type(column.get('type')) is not str):
                    _unavailable()
                normalized.append({'name': column['name'], 'type': column['type']})
            if columns is not None and columns != normalized:
                _unavailable()
            columns = normalized
        elif columns is not None or data:
            _unavailable()
        if any(type(item) is not list or len(item) != len(columns or []) for item in data):
            _unavailable()
        rows.extend(data)
    columns = columns or []
    last = pages[-1]
    truncated = any(page.get('truncated', False) is True for page in pages)
    partial = bool(last.get('next_uri')) or last.get('state') != 'FINISHED' or state != 'FINISHED' or truncated
    range_info = dict(returned_rows=len(rows), saved_rows=len(rows), state=state,
                      partial=partial, truncated=truncated)
    query = dict(query_id=query_id, request_id=body['request_id'], worksheet_id=body['worksheet_id'], context=context)
    try:
        content = _serialize(body['format'], columns, rows, range_info, query)
    except (ValueError, TypeError, UnicodeError, RecursionError, OverflowError):
        _unavailable()
    current = qs._owned(principal, query_id, selected_role, cleanup=False)
    if current['execution_closure']:
        raise QueryError('EXECUTION_CLOSED', 409)
    if qs._metadata(current) != context or any(current[k] != row[k] for k in
            ('request_id', 'worksheet_id', 'backend_query_id', 'state')):
        _unavailable()
    return dict(format=body['format'], filename='query-result-' + query_id + '.' + body['format'],
        content_type=CONTENT_TYPES[body['format']], content_base64=base64.b64encode(content).decode('ascii'),
        **query, **range_info)


def dispatch(handler, method, url, principal, role):
    """One strict adapter used by Workbench and the native gateway surface."""
    match = re.fullmatch(r'/api/v1/queries/([a-zA-Z0-9-]+)/results/export', url.path)
    if match is None:
        return False
    if method != 'POST':
        raise QueryError('QUERY_NOT_FOUND', 404)
    if '?' in handler.path or '#' in handler.path or url.query or url.fragment or url.scheme or url.netloc:
        raise QueryError('INVALID_RESULT_EXPORT', 400)
    from workbench_server import WorkbenchHandler, request_origin_allowed
    if handler.headers.get('Origin') and not request_origin_allowed(handler.headers):
        raise QueryError('INVALID_ORIGIN', 403)
    lengths = handler.headers.get_all('Content-Length', [])
    if (len(lengths) != 1 or not re.fullmatch(r'[0-9]+', lengths[0]) or
            handler.headers.get_all('Transfer-Encoding', []) or
            len(handler.headers.get_all('Content-Type', [])) != 1):
        raise QueryError('INVALID_RESULT_EXPORT', 400)
    body = WorkbenchHandler.database_body(handler)
    handler.respond(export(principal, match[1], role, body))
    return True
